function explainDifficultyAndHazard(window, stdHrz, xCenterLeft, xCenterRight, leftBound, rightBound, ...
    yCenterTri, stdVert, xPosLeft, xPosRight, yPos, isConvex, defTriCol, red, white, spaceKey, ...
    frameTime, newHeight)

introText = ['You have now finished training. In the upcoming task, the difficulty\n\n' ...
    'of figuring out the source will vary across blocks. This difficulty\n\n' ...
    'refers to how spread out the possible target positions are around\n\n' ...
    'each triangle. There are three difficulty levels: Easy, Medium, and\n\n' ...
    'Hard. Press space to see a demonstration of each difficulty level.'];
blockInstructions(window, introText, white, spaceKey, frameTime);

diffLabels = {'Easy', 'Medium', 'Hard'};
for d = 1:length(stdHrz)
    textTop = sprintf(['This is an example of the **%s** difficulty level.\n\n' ...
        'Notice how spread out the possible target positions are.'], diffLabels{d});
    textBottom = 'Press space to continue.';
    drawDist(xCenterLeft, leftBound, rightBound, stdHrz(d), xCenterLeft, xCenterRight, ...
        window, textTop, textBottom, white, newHeight, defTriCol, xPosLeft, xPosRight, ...
        yPos, isConvex, red, spaceKey, yCenterTri, stdVert, frameTime);
end

freqText = ['In addition to difficulty, how often the source switches between\n\n' ...
    'the left and right triangle will also vary across blocks. During\n\n' ...
    'training, the source switched at what will be called the\n\n' ...
    '''Low Frequency'' rate. In some blocks of the upcoming task, the\n\n' ...
    'source will continue to switch at this ''Low Frequency'' rate.\n\n' ...
    'In other blocks, the source will switch more often than it did during\n\n' ...
    'training; this will be called the ''High Frequency'' rate.\n\n\n' ...
    'Before each block begins, you will be told that block''s difficulty\n\n' ...
    'level and switching rate. Press space to begin the task.'];
blockInstructions(window, freqText, white, spaceKey, frameTime);

end