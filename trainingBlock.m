function [data, frameNum, accuracyData] = trainingBlock(window, f, bl, frameNum, data, ...
    white, grey, green, orange, red, defTriCol, x1, x3, xOffset, yCenterTri, ...
    anglesRad, radius, isConvex, newWidth, newHeight, frameTime, slack, numDistractors, ...
    H, spaceKey, currStdHrz, stdIdx, hazIdx, stdVert, doingEyetracking, target, distractor, vbl, ...
    xCenterLeft, xCenterRight, leftBound, rightBound, xPosLeft, xPosRight, yPos, numMainBlocks)

feedbackTr = 3;
nonFeedbackTr = 2;

givingFeedback = 1;
showInstruction = 1;
showAccuracy = 0;
mb = 0; % training is not one of the 6 randomized main blocks

for tr = 1:feedbackTr
    % define parameters that change throughout blocks
    switch tr
        case 1
            distractors = 0;
            endAudio = 0;
            instructions1 = ['This is the first part of the training block. In this\n\n' ...
                'part, a target ''T'' will appear on the screen and you must determine\n\n' ...
                'which triangle is currently generating the target. Press space to\n\n' ...
                'continue.'];
            instructions2 = ['If you believe the **left** triangle is generating the\n\n' ...
                'target, press the ''F'' key once. If you believe the **right**\n\n' ...
                'triangle is generating the target, press the ''J'' key once.\n\n' ...
                'You may do this as many times as you feel are necessary\n\n' ...
                'throughout the task. The triangle that you have indicated\n\n' ...
                'to be the source will be highlighted in green. A buzz will\n\n' ...
                'play while your current indication is incorrect.\n\n' ...
                'Press space to begin.'];
        case 2
            distractors = numDistractors/2;
            endAudio = 0;
            instructions1 = ['This is the second part of the training block. In this\n\n' ...
                'part, a target ''T'' will appear on the screen and you must determine\n\n' ...
                'which triangle is currently generating the target. The only difference\n\n' ...
                'is that there will be distractors (''L'') on the screen that are the\n\n' ...
                'same color as the target. Their positions are randomly generated and\n\n' ...
                'do not depend on the source at all. Everything else remains the same.\n\n' ...
                'Press space to continue.'];
            instructions2 = ['Reminder: If you believe the **left** triangle is generating the\n\n' ...
                'target, press the ''F'' key once. If you believe the **right**\n\n' ...
                'triangle is generating the target, press the ''J'' key once.\n\n' ...
                'You may do this as many times as you feel are necessary\n\n' ...
                'throughout the task. The triangle that you have indicated\n\n' ...
                'to be the source will be highlighted in green. A buzz will\n\n' ...
                'play while your current indication is incorrect.\n\n' ...
                'Press space to begin.'];
        case 3
            distractors = numDistractors;
            endAudio = 1;
            instructions1 = ['This is the final part of the feedback segment of the training block. In this\n\n' ...
                'part, a target ''T'' will appear on the screen and you must determine\n\n' ...
                'which triangle is currently generating the target. The only difference\n\n' ...
                'is that there will be twice as many distractors (''L'') on the screen\n\n' ...
                'as the last part, which is how many there will be for the task.\n\n' ...
                'Everything else remains the same.\n\n' ...
                'Press space to continue.'];
            instructions2 = ['Reminder: If you believe the **left** triangle is generating the\n\n' ...
                'target, press the ''F'' key once. If you believe the **right**\n\n' ...
                'triangle is generating the target, press the ''J'' key once.\n\n' ...
                'You may do this as many times as you feel are necessary\n\n' ...
                'throughout the task. The triangle that you have indicated\n\n' ...
                'to be the source will be highlighted in green. A buzz will\n\n' ...
                'play while your current indication is incorrect.\n\n' ...
                'Press space to begin.'];
    end

    [data, frameNum, accuracy] = runTrials(window, f, bl, mb, numMainBlocks, frameNum, data, ...
        white, grey, green, orange, red, defTriCol, x1, x3, xOffset, yCenterTri, ...
        anglesRad, radius, isConvex, newWidth, newHeight, frameTime, slack, distractors, ...
        H, spaceKey, currStdHrz, stdIdx, hazIdx, stdVert, doingEyetracking, target, distractor, ...
        givingFeedback, instructions1, instructions2, showInstruction, ...
        showAccuracy, vbl, endAudio, xCenterLeft, xCenterRight, leftBound, ...
        rightBound, xPosLeft, xPosRight, yPos);

    accuracyData(tr).trialAccuracy = accuracy;

end

instructions1 = ['The final part of training will consist of two\n\n' ...
    'trials that are each two minutes long with the number of\n\n' ...
    'distractors that will be used in the task. This will look the\n\n' ...
    'same as the training part you just completed, except you will\n\n' ...
    'not receive feedback when your current belief is incorrect.\n\n' ...
    'Instead, you will be told your accuracy at the end of each trial.'];
instructions2 = ['Reminder: If you believe the **left** triangle is generating the\n\n' ...
    'target, press the ''F'' key once. If you believe the **right**\n\n' ...
    'triangle is generating the target, press the ''J'' key once.\n\n' ...
    'You may do this as many times as you feel are necessary\n\n' ...
    'throughout the task. The triangle that you have indicated\n\n' ...
    'to be the source will be highlighted in green.\n\n' ...
    'Press space to begin.'];

% go through instructions at the beginning of each block
blockInstructions(window, instructions1, white, spaceKey, frameTime);
blockInstructions(window, instructions2, white, spaceKey, frameTime);

givingFeedback = 0;
showInstruction = 0;
showAccuracy = 1;
endAudio = 0;

for tr = 1:nonFeedbackTr

    [data, frameNum, accuracy] = runTrials(window, f, bl, mb, numMainBlocks, frameNum, data, ...
        white, grey, green, orange, red, defTriCol, x1, x3, xOffset, yCenterTri, ...
        anglesRad, radius, isConvex, newWidth, newHeight, frameTime, slack, distractors, ...
        H, spaceKey, currStdHrz, stdIdx, hazIdx, stdVert, doingEyetracking, target, distractor, ...
        givingFeedback, instructions1, instructions2, showInstruction, ...
        showAccuracy, vbl, endAudio, xCenterLeft, xCenterRight, leftBound, ...
        rightBound, xPosLeft, xPosRight, yPos);

    accuracyData(tr + feedbackTr).trialAccuracy = accuracy;
end

save('accuracy.mat', 'accuracyData');
end